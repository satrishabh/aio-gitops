package com.aio.platform.service;

import java.util.Locale;

/**
 * The bash script an admin runs once against a new cluster (Clusters → Add cluster, step 2). It creates a limited
 * service account for AIO and Argo CD and prints its token and CA as one line of JSON to paste back into the portal.
 * The script itself contains no secrets: everything it prints is read from the cluster it runs against.
 */
public final class BootstrapScript {
    private BootstrapScript() {}

    public static final String NAMESPACE = "aio-system";
    public static final String SERVICE_ACCOUNT = "aio-deployer";
    public static final String TOKEN_SECRET = "aio-deployer-token";
    /** Cluster-wide rights: namespaces AIO creates, read-only health data, binding the app role per namespace. */
    public static final String CLUSTER_ROLE = "aio-deployer";
    /** What Argo CD and AIO need inside one app namespace; only ever bound per namespace (RoleBinding). */
    public static final String APP_ROLE = "aio-deployer-apps";
    public static final String ROLE_BINDING = "aio-deployer";

    /** Name of the downloadable file. */
    public static String fileName(String cluster) {
        return "aio-bootstrap-" + cluster + ".sh";
    }

    /** The script for one cluster. {@code server} is what the admin entered, only used to warn on a kubectl context mismatch. */
    public static String render(String cluster, String cloud, String server) {
        if (cluster == null || !cluster.matches("[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?")) throw new IllegalArgumentException("invalid cluster name");
        String c = cloud == null ? "other" : cloud.toLowerCase(Locale.ROOT);
        if (!EnvironmentRegistry.CLOUDS.contains(c)) throw new IllegalArgumentException("invalid cloud");
        String srv = server == null ? "" : server.trim();
        if (!srv.isEmpty() && !srv.matches("https://[A-Za-z0-9.:\\[\\]-]+(/[A-Za-z0-9._/-]*)?"))
            throw new IllegalArgumentException("API server must be an https:// URL");
        return TEMPLATE
                .replace("@CLUSTER@", cluster)
                .replace("@CLOUD@", c)
                .replace("@SERVER@", srv)
                .replace("@NS@", NAMESPACE)
                .replace("@SA@", SERVICE_ACCOUNT)
                .replace("@TOKEN@", TOKEN_SECRET)
                .replace("@CR@", CLUSTER_ROLE)
                .replace("@APPROLE@", APP_ROLE)
                .replace("@CRB@", ROLE_BINDING);
    }

    private static final String TEMPLATE = """
            #!/usr/bin/env bash
            # AIO bootstrap for cluster "@CLUSTER@" (@CLOUD@). Generated by the AIO portal; contains no secrets.
            #
            # Run it ONCE with kubectl pointing at the NEW cluster, as someone allowed to create RBAC there:
            #     bash aio-bootstrap-@CLUSTER@.sh                # set up; prints one line of JSON
            #     KUBE_CONTEXT=my-ctx bash aio-bootstrap-@CLUSTER@.sh   # pick a kubeconfig context explicitly
            #     bash aio-bootstrap-@CLUSTER@.sh --revoke       # remove everything it created (see REVOKE below)
            # Safe to re-run (idempotent): it applies the same objects and prints the same token.
            #
            # What it creates on this cluster:
            #   namespace @NS@, ServiceAccount @NS@/@SA@ and its long-lived token Secret @NS@/@TOKEN@;
            #   ClusterRole @CR@ + ClusterRoleBinding @CRB@ (cluster-wide, for the token):
            #     - namespaces: get, list, watch, create, patch (AIO creates each environment's namespace);
            #     - nodes, pods, events, CustomResourceDefinitions: get, list, watch (read-only health checks);
            #     - rolebindings: get, create, and "bind" on ClusterRole @APPROLE@ ONLY (see next point);
            #   ClusterRole @APPROLE@: what Argo CD needs inside an app namespace (Deployments, Services, Ingresses,
            #     ConfigMaps, Secrets, PDBs, HPAs, NetworkPolicies, LimitRanges, Rollouts, Traefik Middlewares, ...).
            #     It is NOT bound cluster-wide: AIO binds it per environment namespace it creates (RoleBinding @CRB@).
            #
            # What the token can NOT do: create or change ClusterRoles/ClusterRoleBindings, read Secrets outside the
            # namespaces @APPROLE@ is bound in, touch nodes, or grant itself any right beyond @APPROLE@. Note: since it may
            # bind @APPROLE@, it could bind it in any namespace; keep that in mind for namespaces holding other secrets.
            #
            # The JSON line printed at the end holds the token: paste it into AIO (Clusters -> Add cluster, step 3) and do
            # not store it anywhere else. AIO keeps it only in the Argo CD cluster Secret on the hub, never in its database.
            #
            # REVOKE (stops AIO and Argo CD at once; apps already running keep running):
            #     bash aio-bootstrap-@CLUSTER@.sh --revoke
            #   or by hand:
            #     kubectl delete clusterrolebinding @CRB@
            #     kubectl delete rolebinding -A -l aio.platform/deployer=true
            #     kubectl delete namespace @NS@          # deletes the ServiceAccount and invalidates the token
            #     kubectl delete clusterrole @CR@ @APPROLE@
            #   then remove the cluster in AIO (Clusters -> Remove) so Argo CD forgets it.
            set -euo pipefail

            EXPECTED_SERVER="@SERVER@"
            k() { if [ -n "${KUBE_CONTEXT:-}" ]; then kubectl --context "$KUBE_CONTEXT" "$@"; else kubectl "$@"; fi; }
            say() { echo "$*" >&2; }

            command -v kubectl >/dev/null || { say "kubectl not found"; exit 1; }
            CURRENT_SERVER="$(k config view --minify -o jsonpath='{.clusters[0].cluster.server}')"
            say "AIO bootstrap for @CLUSTER@ on $(k config current-context 2>/dev/null || echo '?') ($CURRENT_SERVER)"
            if [ -n "$EXPECTED_SERVER" ] && [ "$CURRENT_SERVER" != "$EXPECTED_SERVER" ]; then
              say "WARNING: kubectl points at $CURRENT_SERVER but AIO was told $EXPECTED_SERVER."
              say "         Continue only if both are the same cluster (e.g. private vs public endpoint)."
            fi

            if [ "${1:-}" = "--revoke" ]; then
              say "Revoking AIO access to this cluster..."
              k delete clusterrolebinding @CRB@ --ignore-not-found
              k delete rolebinding -A -l aio.platform/deployer=true --ignore-not-found
              k delete namespace @NS@ --ignore-not-found
              k delete clusterrole @CR@ @APPROLE@ --ignore-not-found
              say "Done. Environment namespaces and the apps in them were left as they are."
              exit 0
            fi

            k apply -f - >&2 <<'YAML'
            apiVersion: v1
            kind: Namespace
            metadata:
              name: @NS@
              labels: { aio.platform/managed: "true" }
            ---
            apiVersion: v1
            kind: ServiceAccount
            metadata: { name: @SA@, namespace: @NS@ }
            ---
            apiVersion: v1
            kind: Secret
            metadata:
              name: @TOKEN@
              namespace: @NS@
              annotations: { kubernetes.io/service-account.name: @SA@ }
            type: kubernetes.io/service-account-token
            ---
            apiVersion: rbac.authorization.k8s.io/v1
            kind: ClusterRole
            metadata: { name: @CR@, labels: { aio.platform/deployer: "true" } }
            rules:
              - apiGroups: [""]
                resources: ["namespaces"]
                verbs: ["get", "list", "watch", "create", "patch"]
              - apiGroups: [""]
                resources: ["nodes", "pods", "events"]
                verbs: ["get", "list", "watch"]
              - apiGroups: ["apiextensions.k8s.io"]
                resources: ["customresourcedefinitions"]
                verbs: ["get", "list", "watch"]
              - apiGroups: ["rbac.authorization.k8s.io"]
                resources: ["rolebindings"]
                verbs: ["get", "create"]
              - apiGroups: ["rbac.authorization.k8s.io"]
                resources: ["clusterroles"]
                resourceNames: ["@APPROLE@"]
                verbs: ["bind"]
            ---
            apiVersion: rbac.authorization.k8s.io/v1
            kind: ClusterRole
            metadata: { name: @APPROLE@, labels: { aio.platform/deployer: "true" } }
            rules:
              - apiGroups: [""]
                resources: ["pods", "services", "endpoints", "configmaps", "secrets", "serviceaccounts",
                            "persistentvolumeclaims", "limitranges"]
                verbs: ["get", "list", "watch", "create", "update", "patch", "delete"]
              - apiGroups: [""]
                resources: ["pods/log", "events", "resourcequotas"]
                verbs: ["get", "list", "watch"]
              - apiGroups: ["apps"]
                resources: ["deployments", "deployments/scale", "replicasets", "statefulsets"]
                verbs: ["get", "list", "watch", "create", "update", "patch", "delete"]
              - apiGroups: ["batch"]
                resources: ["jobs", "cronjobs"]
                verbs: ["get", "list", "watch", "create", "update", "patch", "delete"]
              - apiGroups: ["autoscaling"]
                resources: ["horizontalpodautoscalers"]
                verbs: ["get", "list", "watch", "create", "update", "patch", "delete"]
              - apiGroups: ["policy"]
                resources: ["poddisruptionbudgets"]
                verbs: ["get", "list", "watch", "create", "update", "patch", "delete"]
              - apiGroups: ["networking.k8s.io"]
                resources: ["ingresses", "networkpolicies"]
                verbs: ["get", "list", "watch", "create", "update", "patch", "delete"]
              - apiGroups: ["discovery.k8s.io"]
                resources: ["endpointslices"]
                verbs: ["get", "list", "watch"]
              - apiGroups: ["argoproj.io"]
                resources: ["rollouts", "rollouts/status", "analysisruns", "analysistemplates", "experiments"]
                verbs: ["get", "list", "watch", "create", "update", "patch", "delete"]
              - apiGroups: ["traefik.io", "traefik.containo.us"]
                resources: ["middlewares"]
                verbs: ["get", "list", "watch", "create", "update", "patch", "delete"]
              - apiGroups: ["cert-manager.io"]
                resources: ["certificates", "certificaterequests"]
                verbs: ["get", "list", "watch"]
            ---
            apiVersion: rbac.authorization.k8s.io/v1
            kind: ClusterRoleBinding
            metadata: { name: @CRB@, labels: { aio.platform/deployer: "true" } }
            subjects: [{ kind: ServiceAccount, name: @SA@, namespace: @NS@ }]
            roleRef: { apiGroup: rbac.authorization.k8s.io, kind: ClusterRole, name: @CR@ }
            YAML

            say "Waiting for the token..."
            TOKEN=""
            for _ in $(seq 1 30); do
              TOKEN="$(k -n @NS@ get secret @TOKEN@ -o jsonpath='{.data.token}' 2>/dev/null || true)"
              [ -n "$TOKEN" ] && break
              sleep 1
            done
            [ -n "$TOKEN" ] || { say "The token was not issued (is the token controller running?)"; exit 1; }
            TOKEN="$(printf '%s' "$TOKEN" | base64 --decode)"
            CA="$(k -n @NS@ get secret @TOKEN@ -o jsonpath='{.data.ca\\.crt}')"

            say ""
            say "Paste the next line into AIO (Clusters -> Add cluster -> step 3). It contains the token: do not save it."
            printf '{"cluster":"%s","server":"%s","token":"%s","caData":"%s"}\\n' "@CLUSTER@" "$CURRENT_SERVER" "$TOKEN" "$CA"
            """;
}
