// Run against a local preview only; API fixtures avoid needing a real login.
const { chromium } = require(process.argv[2] || 'playwright')
const assert = require('node:assert/strict')
const { join } = require('node:path')
const { tmpdir } = require('node:os')

;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
    const page = await context.newPage()
    const base = process.argv[3] || 'http://127.0.0.1:4173'
    assert.ok(new URL(base).hostname === '127.0.0.1', 'Workspace fixture checks must run locally')
    await page.goto(`${base}/login`)
    const trigger = page.getByRole('button', { name: 'Switch to dark appearance' })
    await trigger.tap()
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark')
    assert.equal(await page.getByRole('radiogroup', { name: 'Appearance' }).count(), 0)
    await page.route('**/api/**', route => route.fulfill({ json: route.request().url().endsWith('/api/me')
      ? { name: 'UI test user', login: 'ui-test', accessTier: 'business' } : [] }))
    await page.goto(`${base}/projects`)
    const nav = page.getByRole('navigation', { name: 'Main', exact: true })
    assert.equal(await nav.isVisible(), false, 'Mobile navigation is initially hidden')
    assert.equal(await page.getByRole('navigation', { name: 'Breadcrumb' }).isVisible(), false, 'No redundant mobile page name')
    const menu = page.getByRole('button', { name: 'Open navigation' })
    await menu.tap()
    assert.equal(await nav.isVisible(), true)
    assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden')
    await page.screenshot({ path: join(tmpdir(), 'aio-mobile-navigation.png'), fullPage: true })
    await page.keyboard.press('Escape')
    assert.equal(await nav.isVisible(), false)
    assert.equal(await menu.evaluate(el => el === document.activeElement), true)
    await menu.tap()
    await nav.getByRole('link', { name: 'Projects', exact: true }).tap()
    assert.equal(await nav.isVisible(), false, 'Selecting current page also closes drawer')
    for (const width of [320, 390, 760]) {
      await page.setViewportSize({ width, height: 844 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
      assert.equal(await nav.isVisible(), false)
    }
    await page.screenshot({ path: join(tmpdir(), 'aio-mobile-workspace.png'), fullPage: true })
    await page.setViewportSize({ width: 1440, height: 1000 })
    assert.equal(await nav.isVisible(), true, 'Desktop sidebar stays visible')
    assert.equal(await menu.isVisible(), false)
    console.log('PASS: touch appearance, collapsed mobile navigation, drawer dismissal, current-page selection, focus restoration, responsive workspace, desktop sidebar')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
